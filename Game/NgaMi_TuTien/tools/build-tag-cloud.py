"""Build the approved cloud realm labels and their calibrated gem positions.

The socket interiors in these images are dark, opaque pixels, so alpha-hole
detection is not suitable. Coordinates below are measured on the source PNGs
as percentages of their original canvas, before the transparent margins are
cropped. Recheck them if the artwork is replaced.
"""
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "src/assets/raw/tag_canh_gioi_chu_sang"
OUT = ROOT / "src/assets/game/tag_cloud"
LAYOUT = ROOT / "src/tag-layout-cloud.js"
WIDTH = 420

# source suffix: (game sprite, socket centers x%, center y%, interior diameter%)
MAP = {
    "luyen_khi": ("luyenKhi", [29.4, 34.7, 40.1, 45.2, 50.4, 55.7, 61.1, 66.4, 71.8], 74.1, 3.2),
    "truc_co": ("trucCo", [38.1, 46.0, 53.9, 61.9], 75.0, 4.7),
    "ket_dan": ("ketDan", [39.1, 46.8, 54.4, 62.0], 76.0, 4.7),
    "nguyen_anh": ("nguyenAnh", [38.1, 45.8, 53.7, 61.5], 76.4, 4.5),
    "hoa_than": ("hoaThan", [39.0, 46.7, 54.2, 61.9], 76.2, 4.4),
    "luyen_hu": ("luyenHu", [38.6, 46.4, 54.1, 61.8], 74.1, 4.5),
    "hop_the": ("hopThe", [34.7, 45.9, 57.4, 67.1], 84.7, 4.3),
    "dai_thua": ("daiThua", [35.1, 45.3, 56.0, 66.7], 83.9, 4.5),
    "do_kiep": ("doKiep", [42.5, 47.6, 53.0, 58.1], 84.6, 2.8),
    "chan_tien": ("chanTien", [], 0, 0),
}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    layout = {}
    for suffix, (sprite, gx, gy, gd) in MAP.items():
        image = Image.open(RAW / ("tag_" + suffix + ".png")).convert("RGBA")
        source_w, source_h = image.size
        box = image.getchannel("A").point(lambda alpha: 255 if alpha > 24 else 0).getbbox()
        if not box:
            raise ValueError("Ảnh trống: " + suffix)
        image = image.crop(box)
        width, height = image.size
        key = "tag_" + sprite
        layout[key] = {
            "r": round(width / height, 3),
            "gx": [round((x * source_w / 100 - box[0]) * 100 / width, 2) for x in gx],
            "gy": round((gy * source_h / 100 - box[1]) * 100 / height, 2) if gx else 0,
            "gd": round(gd * source_w / width, 2) if gx else 0,
        }
        out = image.resize((WIDTH, round(height * WIDTH / width)), Image.Resampling.LANCZOS)
        out.save(OUT / (key + ".webp"), "WEBP", quality=92, alpha_quality=100, method=5)
        print(key, out.size, "sockets", len(gx))
    LAYOUT.write_text(
        "/* Generated by tools/build-tag-cloud.py; coordinates refer to the cropped artwork. */\n"
        "(function (root) { root.NgaMi = Object.assign(root.NgaMi || {}, { TAG_LAYOUT_CLOUD: "
        + json.dumps(layout, ensure_ascii=False, separators=(",", ":"))
        + " }); }(typeof self !== \"undefined\" ? self : this));\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
